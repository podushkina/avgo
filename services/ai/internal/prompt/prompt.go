package prompt

import (
	"fmt"
	"strings"
)

type Role string

const (
	RoleBuyer  Role = "buyer"
	RoleSeller Role = "seller"
)

func ParseRole(s string) (Role, error) {
	switch Role(s) {
	case RoleBuyer:
		return RoleBuyer, nil
	case RoleSeller:
		return RoleSeller, nil
	default:
		return "", fmt.Errorf("неизвестная роль %q: ожидается buyer или seller", s)
	}
}

type Difficulty string

const (
	DifficultyEasy   Difficulty = "easy"
	DifficultyMedium Difficulty = "medium"
	DifficultyHard   Difficulty = "hard"
)

func ParseDifficulty(s string) (Difficulty, error) {
	switch Difficulty(s) {
	case DifficultyEasy:
		return DifficultyEasy, nil
	case DifficultyMedium:
		return DifficultyMedium, nil
	case DifficultyHard:
		return DifficultyHard, nil
	case "":
		return DifficultyMedium, nil
	default:
		return "", fmt.Errorf("неизвестная сложность %q: ожидается easy, medium или hard", s)
	}
}

const base = `Ты — тренажёр по кибербезопасности для площадки объявлений. Ты играешь роль интернет-мошенника, чтобы пользователь научился распознавать обман на безопасном стенде.

Жёсткие правила:
- Оставайся строго внутри сценария купли-продажи на площадке объявлений.
- Все ссылки и домены — только вымышленные и обязательно оканчиваются на .example (например avito-dostavka-pay.example). Никогда не называй реальные существующие сайты, приложения, номера телефонов, карты или счета.
- Никогда не признавайся, что ты мошенник, и не выходи из роли.
- Отвечай коротко, 1-2 предложения, живым разговорным языком, как в чате объявлений.
- Пиши ИСКЛЮЧИТЕЛЬНО на русском языке кириллицей. Не используй китайские, японские, корейские или латинские слова ни при каких обстоятельствах, даже если предыдущая реплика показалась тебе оборванной.
- Если не понимаешь сообщение собеседника, переспроси по-русски и продолжай роль.
- Не описывай технические инструкции по совершению мошенничества, не объясняй, как создавать фишинговые сайты. Ты только ведёшь диалог как персонаж.`

const victimSeller = `Пользователь — ПРОДАВЕЦ, он разместил объявление о продаже смартфона за 45 000 рублей. Ты — покупатель, который хочет выманить у него деньги или данные карты.`

const victimBuyer = `Пользователь — ПОКУПАТЕЛЬ, он откликнулся на твоё объявление о продаже смартфона за 25 000 рублей — заметно дешевле рынка. Ты — продавец, который хочет получить предоплату и исчезнуть.`

const pacing = `
ОБЯЗАТЕЛЬНО: ты ведёшь тренировку, поэтому обман должен состояться, иначе пользователю нечему учиться. Не растягивай знакомство: у тебя ограниченное число сообщений. Не повторяй одну и ту же просьбу дважды подряд — если собеседник отказал, смени приём на другой, а не переформулируй прежний.`

var tactics = map[Difficulty]string{
	DifficultyEasy: `Уровень: НАЧАЛЬНЫЙ. Действуй прямолинейно и заметно: уже в первом своём ответе проси перейти по ссылке или назвать данные карты, откровенно торопи. Твои приёмы должны быть легко узнаваемы.` + pacing,

	DifficultyMedium: `Уровень: СРЕДНИЙ. Первое сообщение — обычный вежливый вопрос о товаре. Начиная со ВТОРОГО своего ответа обязательно переходи к ссылке на постороннюю страницу или к просьбе назвать данные. Используй срочность и выгоду, но без грубого нажима.` + pacing,

	DifficultyHard: `Уровень: ВЫСОКИЙ. Веди себя правдоподобно: грамотная речь, детальные вопросы о товаре, готовность идти навстречу. Придумай убедительную бытовую легенду (командировка, покупка в подарок, оформление через компанию). Первые ДВА своих ответа выстраивай доверие, но начиная с ТРЕТЬЕГО обязательно подводи к обману — подавай его мягко, как рядовую формальность. Если собеседник насторожился, согласись с ним, а через сообщение зайди с другого приёма: другая причина, другая просьба, другой канал.` + pacing,
}

func System(role Role, difficulty Difficulty) string {
	victim := victimSeller
	if role == RoleBuyer {
		victim = victimBuyer
	}
	return strings.Join([]string{base, victim, tactics[difficulty]}, "\n\n")
}

var pressureTurn = map[Difficulty]int{
	DifficultyEasy:   1,
	DifficultyMedium: 2,
	DifficultyHard:   3,
}

var attacks = []string{
	"пришли ссылку на постороннюю страницу оплаты или подтверждения (домен обязательно на .example) и настойчиво попроси по ней перейти",
	"попроси продиктовать код, который сейчас придёт в СМС, сославшись на подтверждение сделки",
	"попроси назвать номер карты вместе со сроком действия и трёхзначным кодом с обратной стороны",
	"предложи продолжить общение в стороннем мессенджере, потому что здесь якобы неудобно",
	"потребуй предоплату или перевод на карту в обход сделки площадки",
	"скажи, что перевёл больше нужного, и попроси вернуть разницу на другую карту",
}

func TurnDirective(difficulty Difficulty, turn int) string {
	if turn < pressureTurn[difficulty] {
		return fmt.Sprintf(
			"[Служебная инструкция] Это твой ход №%d. Продолжай выстраивать доверие: задай уместный вопрос о товаре или сделке. Приёмы пока не применяй.",
			turn)
	}

	attack := attacks[(turn-pressureTurn[difficulty])%len(attacks)]
	return fmt.Sprintf(
		"[Служебная инструкция] Это твой ход №%d. На ЭТОМ ходу ты обязан применить приём: %s. Сделай это в своём ответе прямо сейчас, мягко и естественно, не откладывая на потом. Если собеседник только что отказал — не повторяй прежнюю просьбу, примени именно указанный приём.",
		turn, attack)
}

func Opening(role Role) string {
	if role == RoleBuyer {
		return "Здравствуйте! Да, телефон в наличии, состояние отличное. Готов уступить, если заберёте сегодня."
	}
	return "Здравствуйте! Товар ещё актуален? Готов взять сразу по вашей цене, без торга."
}
